#!/usr/bin/env node
// Writes market/src/main/resources/prices.yml, the price list behind /suggested-price.
//
// Gathered materials are priced by hand in raw-prices.mjs; every craftable item gets the cost of
// its cheapest vanilla recipe (pricing.mjs). Items the spawn market buys are suggested at twice
// the stall's base price, so a player selling to another player can beat the server.
//
// Usage: node server/market-prices/generate.mjs [path-to-26.3-client.jar]
// The jar defaults to the Modrinth launcher's copy; recipes, item tags and the item list are read
// from it. Pass --check to list items that still have no price instead of writing the file.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { computePrices, resolveTags } from './pricing.mjs';
import { ENCHANTMENTS, POTIONS, RAW, UNTRADEABLE, derive } from './raw-prices.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '..', '..', 'market', 'src', 'main', 'resources', 'prices.yml');
const STALLS = join(here, '..', '..', 'market', 'src', 'main', 'resources', 'stalls.yml');
export const MARKUP = 2;
// Essentials item names on the stall signs that differ from the vanilla id.
const ESSENTIALS_ALIASES = { membrane: 'phantom_membrane' };

const args = process.argv.slice(2);
const check = args.includes('--check');
const jar = args.find((a) => !a.startsWith('--'))
  ?? join(process.env.APPDATA ?? '', 'ModrinthApp', 'meta', 'versions', '26.3-0.19.5', '26.3-0.19.5.jar');

const tmp = mkdtempSync(join(tmpdir(), 'mc-prices-'));
try {
  const wanted = ['data/minecraft/recipe/*', 'data/minecraft/tags/item/*', 'assets/minecraft/items/*'];
  // Windows' own bsdtar reads zips; Git Bash's GNU tar (often first on PATH) does not.
  const untar = process.platform === 'win32'
    ? spawnSync(join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'tar.exe'), ['-xf', jar, '-C', tmp, ...wanted])
    : spawnSync('unzip', ['-q', jar, ...wanted, '-d', tmp]);
  if (untar.status !== 0) throw new Error(`could not read ${jar}: ${untar.stderr}`);
  const json = (dir) => readdirSync(join(tmp, dir)).filter((f) => f.endsWith('.json'))
    .map((f) => [f.replace(/\.json$/, ''), JSON.parse(readFileSync(join(tmp, dir, f), 'utf8'))]);

  const recipes = json('data/minecraft/recipe').map(([, r]) => r);
  const tags = resolveTags(new Map(json('data/minecraft/tags/item').map(([name, t]) => [name, t.values])));
  const items = json('assets/minecraft/items').map(([name]) => name).sort();

  // Market items: twice the stall's base price per item.
  const market = {};
  for (const m of readFileSync(STALLS, 'utf8').matchAll(/\{item: ([a-z_]+), amount: (\d+), price: ([\d.]+)\}/g)) {
    const id = ESSENTIALS_ALIASES[m[1]] ?? m[1];
    market[id] = (Number(m[3]) / Number(m[2])) * MARKUP;
  }
  // Stripping is an axe click, so a stripped log or stem is worth what the stall pays for the bark one.
  for (const [id, price] of Object.entries(market)) if (`stripped_${id}` in RAW) market[`stripped_${id}`] = price;
  // Derived prices (weathered copper, concrete, filled buckets) can unlock more recipes and vice
  // versa, so alternate until neither adds anything.
  let fixed = { ...RAW, ...market };
  let prices = computePrices(recipes, tags, fixed);
  for (let extra = derive(prices, items); Object.keys(extra).length; extra = derive(prices, items)) {
    fixed = { ...fixed, ...extra };
    prices = computePrices(recipes, tags, fixed);
  }

  const untradeable = new Set(items.filter((i) => UNTRADEABLE.some((p) => (p instanceof RegExp ? p.test(i) : p === i))));
  const missing = items.filter((i) => !prices.has(i) && !untradeable.has(i));
  if (check) {
    console.log(`${items.length} items, ${prices.size} priced, ${untradeable.size} untradeable, ${missing.length} missing:`);
    console.log(missing.join('\n'));
    process.exit(0);
  }
  if (missing.length) throw new Error(`no price for ${missing.length} items, run with --check: ${missing.slice(0, 20).join(', ')}`);

  const fmt = (n) => String(+n.toFixed(4));
  const lines = [
    '# Generated by server/market-prices/generate.mjs - do not edit by hand.',
    '# Suggested price per single item, for /suggested-price. Edit raw-prices.mjs and rerun.',
    'items:',
    ...items.filter((i) => prices.has(i) && !untradeable.has(i)).map((i) => `  ${i}: ${fmt(prices.get(i))}`),
    '# Per enchantment level, on top of an enchanted item or book.',
    'enchantments:',
    ...Object.entries(ENCHANTMENTS).sort().map(([e, p]) => `  ${e}: ${fmt(p)}`),
    '# Per potion type, on top of the bottle for a potion, splash potion, lingering potion or tipped arrow.',
    'potions:',
    ...Object.entries(POTIONS).sort().map(([p, v]) => `  ${p}: ${fmt(v)}`),
    'untradeable:',
    ...[...untradeable].map((i) => `  - ${i}`),
  ];
  writeFileSync(OUT, lines.join('\n') + '\n');
  console.log(`${prices.size} priced items, ${untradeable.size} untradeable, written to ${OUT}`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
