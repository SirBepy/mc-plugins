// Turns the finished model into the datapack's .mcfunction files, market/stalls.yml and
// model.json (every block, for offline renders). Must run after every phase has written into
// model.blocks/model.phases.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export function emit(model, { MARKET, WANTED }) {
  const { here, CX, CZ, OUTER, CORE, CLEAR_TOP, Y, groundAt, surfaceY, blocks, phases, structureGroups } = model;
  const PACK = join(here, '..', 'datapacks', 'spawn-market');
  const FN = join(PACK, 'data', 'spawn_market', 'function');

  const abs = (u, y, v, state) => `${CX + u} ${y} ${CZ + v} ${state}`;
  const MAX_FILL = 32768;

  function boxFills(x0, y0, z0, x1, y1, z1, state) {
    const out = [];
    const layer = (x1 - x0 + 1) * (z1 - z0 + 1);
    const step = Math.max(1, Math.floor(MAX_FILL / layer));
    for (let y = y0; y <= y1; y += step) {
      out.push(`fill ${x0} ${y} ${z0} ${x1} ${Math.min(y1, y + step - 1)} ${z1} ${state}`);
    }
    return out;
  }

  // Collapses runs of identical blocks along x into fills; everything else is a setblock.
  function emitPhase(last) {
    const byRow = new Map();
    for (const [key, state] of last) {
      const [u, y, v] = key.split(',').map(Number);
      const row = `${y},${v}`;
      if (!byRow.has(row)) byRow.set(row, []);
      byRow.get(row).push([u, state]);
    }
    const lines = [];
    for (const [row, cells] of [...byRow].sort()) {
      const [y, v] = row.split(',').map(Number);
      cells.sort((a, b) => a[0] - b[0]);
      for (let i = 0; i < cells.length;) {
        let j = i;
        while (j + 1 < cells.length && cells[j + 1][0] === cells[j][0] + 1 && cells[j + 1][1] === cells[i][1] && !cells[i][1].includes('{')) j++;
        const [u, state] = cells[i];
        lines.push(j > i ? `fill ${CX + u} ${y} ${CZ + v} ${CX + cells[j][0]} ${y} ${CZ + v} ${state}`
          : `setblock ${abs(u, y, v, state)}`);
        i = j + 1;
      }
    }
    return lines;
  }

  const x0 = CX - OUTER, x1 = CX + OUTER, z0 = CZ - OUTER, z1 = CZ + OUTER;
  const header = (what) => [`# Generated by server/spawn-market/generate.mjs - do not edit by hand. ${what}`];

  // Everything above the new ground goes: trees, grass, the old torches. Per column, so the
  // blend ring (and, past it, any layout-specific terrain like street.mjs's street corridor)
  // keeps whatever natural ground already sits at its target height. Iterating surfaceY itself
  // (not a fixed -OUTER..OUTER square) is what lets street.mjs's columns - outside that square -
  // get cleared/cut for free, with no special-casing here.
  const clear = [...boxFills(CX - CORE, Y + 1, CZ - CORE, CX + CORE, CLEAR_TOP, CZ + CORE, 'air')];
  for (const [key, target] of surfaceY) {
    const [u, v] = key.split(',').map(Number);
    if (Math.abs(u) <= CORE && Math.abs(v) <= CORE) continue; // already in the bulk box above
    clear.push(`fill ${CX + u} ${target + 1} ${CZ + v} ${CX + u} ${CLEAR_TOP} ${CZ + v} air`);
  }
  // Cutting ground down to the plaza (or the street): everything between the new surface and the old one.
  for (const [key, target] of surfaceY) {
    const [u, v] = key.split(',').map(Number);
    const g = groundAt(u, v).y;
    if (g > target) clear.push(`fill ${CX + u} ${target + 1} ${CZ + v} ${CX + u} ${g} ${CZ + v} air`);
  }

  rmSync(FN, { recursive: true, force: true });
  mkdirSync(FN, { recursive: true });
  const write = (name, lines) => writeFileSync(join(FN, `${name}.mcfunction`), lines.join('\n') + '\n');

  write('build', [
    ...header('Entry point.'),
    '# Loads the chunks first: fill/setblock fail on unloaded chunks, and forceload only takes',
    '# effect on a later tick, hence the schedule.',
    `forceload add ${x0} ${z0} ${x1} ${z1}`,
    'tellraw @a {"text":"[spawn-market] building in 2s...","color":"gray"}',
    'schedule function spawn_market:build_run 40t',
  ]);
  write('clear', [...header('Clears trees and cuts the hill.'), ...clear]);
  write('terrain', [...header('Fills, paving, paths.'), ...emitPhase(phases.terrain)]);
  // One .mcfunction per stall/station/shared-structure module (core.mjs's withGroup), instead of
  // one flat structure.mcfunction: build_run calls each in the same order the generator built it
  // in. A group with no build-phase blocks (none currently) writes no file and gets no call.
  const structureCalls = [];
  for (const [name, groupBlocks] of structureGroups()) {
    if (groupBlocks.size === 0) continue;
    write(name, [...header(`Stall/station: ${name}.`), ...emitPhase(groupBlocks)]);
    structureCalls.push(`function spawn_market:${name}`);
  }
  write('build_run', [
    ...header('Runs the phases in order.'),
    'function spawn_market:clear',
    'function spawn_market:terrain',
    ...structureCalls,
    'function spawn_market:attach',
    'kill @e[type=item,x=' + x0 + ',y=' + (Y - 10) + ',z=' + z0 + ',dx=' + (2 * OUTER) + ',dy=60,dz=' + (2 * OUTER) + ']',
    `forceload remove ${x0} ${z0} ${x1} ${z1}`,
    'tellraw @a {"text":"[spawn-market] done","color":"gray"}',
  ]);
  write('attach', [...header('Blocks that need support: signs, lanterns, bell, plants.'), ...emitPhase(phases.attach)]);

  // Item names are Essentials' (its items.json); a sign line fits 15 characters.
  const stallsYml = [
    '# Generated by server/spawn-market/generate.mjs - do not edit by hand.',
    '# The Market plugin picks a few of each stall\'s buys every day and writes them onto its slots.',
    'sign-block: spruce_wall_sign',
    ...(MARKET.priceLectern ? [`price-lectern: {x: ${MARKET.priceLectern.x}, y: ${MARKET.priceLectern.y}, z: ${MARKET.priceLectern.z}, facing: ${MARKET.priceLectern.facing}}`] : []),
    // Heads corner stall (2026-10-09): no fixed buys list like the other stalls below, since the
    // Market plugin fills its 4 slots from More Mob Heads' own head registry, not stalls.yml.
    ...(MARKET.headStall ? [
      'head-stall:',
      `  name: ${MARKET.headStall.name}`,
      `  color: ${MARKET.headStall.color}`,
      '  slots:',
      ...MARKET.headStall.slots.map((s) => `    - {x: ${s.x}, y: ${s.y}, z: ${s.z}, facing: ${s.facing}}`),
    ] : []),
    ...(WANTED ? [
      'wanted-board:',
      `  sign: {x: ${WANTED.sign.x}, y: ${WANTED.sign.y}, z: ${WANTED.sign.z}, facing: ${WANTED.sign.facing}}`,
      `  head: {x: ${WANTED.head.x}, y: ${WANTED.head.y}, z: ${WANTED.head.z}, facing: ${WANTED.head.facing}}`,
    ] : []),
    // Every shop exports `signs:` (a list), even Cosmetics' own 1-element one, so MarketLayout
    // parses one consistent shape for every shop (Joe, 2026-10-09: Homes gets 3, one per home).
    ...(Object.keys(MARKET.shops).length ? [
      'shops:',
      ...Object.entries(MARKET.shops).map(([key, s]) =>
        `  ${key}: {name: ${s.name}, color: ${s.color}, signs: [${s.signs.map((sl) =>
          `{x: ${sl.x}, y: ${sl.y}, z: ${sl.z}, facing: ${sl.facing}}`).join(', ')}]}`),
    ] : []),
    'stalls:',
    ...MARKET.stalls.flatMap(({ id, name, color, slots, buys }) => [
      `  ${id}:`,
      `    name: ${name}`,
      `    color: ${color}`,
      '    slots:',
      ...slots.map((s) => `      - {x: ${s.x}, y: ${s.y}, z: ${s.z}, facing: ${s.facing}}`),
      '    buys:',
      ...buys.map((b) => `      - {item: ${b.item}, amount: ${b.amount}, price: ${b.price}}`),
    ]),
  ];
  writeFileSync(join(here, '..', '..', 'market', 'src', 'main', 'resources', 'stalls.yml'), stallsYml.join('\n') + '\n');

  const modelOut = { origin: [CX, CZ], y: Y, outer: OUTER, clearTop: CLEAR_TOP, surface: Object.fromEntries(surfaceY), blocks: {} };
  for (const [k, s] of blocks) {
    const [u, y, v] = k.split(',').map(Number);
    modelOut.blocks[`${CX + u},${y},${CZ + v}`] = s;
  }
  writeFileSync(join(here, 'model.json'), JSON.stringify(modelOut));
  const count = (n) => readFileSync(join(FN, `${n}.mcfunction`), 'utf8').split('\n').length - 2;
  const structureTotal = structureCalls.reduce((sum, call) => sum + count(call.split(':')[1]), 0);
  console.log(`clear ${count('clear')}, terrain ${count('terrain')}, structure ${structureTotal} across ${structureCalls.length} files, attach ${count('attach')} commands; ${blocks.size} blocks`);
}
